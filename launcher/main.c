// tinyxell launcher: an xsdk title that reads a libxenon homebrew ELF, flattens it into physical memory, fills in the
// tinyxell handoff struct inside the stage1 blob, and has the hypervisor copy stage1 and jump to it. From there stage1
// catches the CPUs and runs the homebrew. If anything goes wrong, it shows a message box and returns to the dashboard.
//
// The ELF is looked for as a file beside the .xex first (game:\<xex stem>.elf, then game:\<xex stem>.elf32), and
// embedded in the stage1 blob second (not yet).

#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "xsdk/kernel.h"
#include "xsdk/log.h"
#include "xsdk/xam.h"

#include "handoff.h"
#include "hv.h"

// The stage1 blob as a C array, generated by xxd from the stage1 build (stage1/build/stage1.h on the include path).
#include "stage1.h"

// ---------------------------------------------------------------------------
// Minimal ELF structures (from xell-reloaded:source/lv1/elf_abi.h)
// ---------------------------------------------------------------------------

#define EI_MAG0    0
#define EI_MAG1    1
#define EI_MAG2    2
#define EI_MAG3    3
#define EI_CLASS   4
#define EI_DATA    5
#define EI_NIDENT  16

#define ELFMAG0    0x7f
#define ELFMAG1    'E'
#define ELFMAG2    'L'
#define ELFMAG3    'F'
#define ELFCLASS32 1
#define ELFDATA2MSB 2
#define EM_PPC     20
#define PT_LOAD    1

typedef struct {
	uint8_t  e_ident[EI_NIDENT];
	uint16_t e_type;
	uint16_t e_machine;
	uint32_t e_version;
	uint32_t e_entry;
	uint32_t e_phoff;
	uint32_t e_shoff;
	uint32_t e_flags;
	uint16_t e_ehsize;
	uint16_t e_phentsize;
	uint16_t e_phnum;
	uint16_t e_shentsize;
	uint16_t e_shnum;
	uint16_t e_shstrndx;
} Elf32_Ehdr;

typedef struct {
	uint32_t p_type;
	uint32_t p_offset;
	uint32_t p_vaddr;
	uint32_t p_paddr;
	uint32_t p_filesz;
	uint32_t p_memsz;
	uint32_t p_flags;
	uint32_t p_align;
} Elf32_Phdr;

// The ELF is big-endian and xsdk's CPU is big-endian, so no byte swapping.

// ---------------------------------------------------------------------------
// Message box helper
// ---------------------------------------------------------------------------

static void show_error(const char *text)
{
	xsdk_log_write("tinyxell: ERROR: %s", text);
	static const uint16_t title[] = { 't', 'i', 'n', 'y', 'x', 'e', 'l', 'l', 0 };
	// Convert the ASCII error to UTF-16 on the stack.
	uint16_t wide[256];
	int i = 0;
	for (; text[i] && i < 254; i++)
		wide[i] = (uint8_t)text[i];
	wide[i] = 0;
	static const uint16_t ok[] = { 'O', 'K', 0 };
	const uint16_t *buttons[] = { ok };
	uint32_t pressed = 0;
	XAM_OVERLAPPED overlapped = { 0 };
	(void)xsdk_xam_message_box(0, title, wide, buttons, 1, &pressed, &overlapped);
	(void)xsdk_xam_wait(&overlapped, 30000, NULL);
}

// ---------------------------------------------------------------------------
// Read a file into a malloc'd buffer
// ---------------------------------------------------------------------------

static void *read_file(const char *path, uint32_t *out_size)
{
	FILE *f = fopen(path, "rb");
	if (!f)
		return NULL;
	fseek(f, 0, SEEK_END);
	long size = ftell(f);
	if (size <= 0 || size > 64 * 1024 * 1024) {
		fclose(f);
		return NULL;
	}
	fseek(f, 0, SEEK_SET);
	void *buf = malloc((size_t)size);
	if (!buf) {
		fclose(f);
		return NULL;
	}
	if (fread(buf, 1, (size_t)size, f) != (size_t)size) {
		free(buf);
		fclose(f);
		return NULL;
	}
	fclose(f);
	*out_size = (uint32_t)size;
	return buf;
}

// ---------------------------------------------------------------------------
// Find the xex's own stem name (e.g. "snes9x" from "snes9x.xex")
// ---------------------------------------------------------------------------

static void xex_stem(char *stem, size_t stem_bytes)
{
	const char *image = ExLoadedImageName ? ExLoadedImageName : "";
	const char *base = image;
	for (const char *c = image; *c; c++) {
		if (*c == '\\' || *c == '/' || *c == ':')
			base = c + 1;
	}
	const char *dot = strrchr(base, '.');
	size_t len = dot ? (size_t)(dot - base) : strlen(base);
	if (len == 0 || len >= stem_bytes)
		len = 0;
	memcpy(stem, base, len);
	stem[len] = '\0';
}

// ---------------------------------------------------------------------------
// Try loading a homebrew ELF from game:\ next to the .xex
// ---------------------------------------------------------------------------

static void *try_load_elf_file(uint32_t *out_size)
{
	char stem[64];
	xex_stem(stem, sizeof stem);
	if (stem[0] == '\0') {
		xsdk_log_write("tinyxell: could not determine the xex name");
		return NULL;
	}

	// Try .elf first, then .elf32, both beside the .xex.
	static const char *extensions[] = { ".elf", ".elf32" };
	for (int i = 0; i < 2; i++) {
		char path[128];
		(void)snprintf(path, sizeof path, "game:\\%s%s", stem, extensions[i]);
		xsdk_log_write("tinyxell: trying %s", path);
		void *buf = read_file(path, out_size);
		if (buf)
			return buf;
	}
	return NULL;
}

// ---------------------------------------------------------------------------
// Parse the ELF and flatten its PT_LOAD segments into physical memory
// ---------------------------------------------------------------------------

// Returns the entry point physical address, or 0 on failure. *out_load_base gets the physical address the image should
// be copied to (the lowest paddr from the ELF, with the 64-bit flag stripped).
static uint32_t flatten_elf(const void *elf_data, uint32_t elf_size,
	uint8_t **out_image, uint32_t *out_image_size, uint32_t *out_bss_size, uint32_t *out_load_base)
{
	if (elf_size < sizeof(Elf32_Ehdr)) {
		show_error("ELF too small");
		return 0;
	}
	const Elf32_Ehdr *ehdr = elf_data;
	if (ehdr->e_ident[EI_MAG0] != ELFMAG0 || ehdr->e_ident[EI_MAG1] != ELFMAG1 ||
		ehdr->e_ident[EI_MAG2] != ELFMAG2 || ehdr->e_ident[EI_MAG3] != ELFMAG3) {
		show_error("not an ELF file");
		return 0;
	}
	if (ehdr->e_ident[EI_CLASS] != ELFCLASS32) {
		show_error("not a 32-bit ELF (Elf64 not yet supported)");
		return 0;
	}
	if (ehdr->e_ident[EI_DATA] != ELFDATA2MSB) {
		show_error("not big-endian");
		return 0;
	}
	if (ehdr->e_machine != EM_PPC) {
		show_error("not PowerPC");
		return 0;
	}
	if (ehdr->e_phnum == 0) {
		show_error("no program headers");
		return 0;
	}

	// First pass: find the extent of the image (lowest paddr to highest paddr + memsz).
	uint32_t lo = UINT32_MAX, hi = 0;
	for (int i = 0; i < ehdr->e_phnum; i++) {
		if ((uint32_t)ehdr->e_phoff + (uint32_t)(i + 1) * sizeof(Elf32_Phdr) > elf_size) {
			show_error("program header past EOF");
			return 0;
		}
		const Elf32_Phdr *phdr = (const Elf32_Phdr *)((const uint8_t *)elf_data + ehdr->e_phoff +
			i * sizeof(Elf32_Phdr));
		if (phdr->p_type != PT_LOAD || phdr->p_memsz == 0)
			continue;
		if (phdr->p_paddr < lo)
			lo = phdr->p_paddr;
		if (phdr->p_paddr + phdr->p_memsz > hi)
			hi = phdr->p_paddr + phdr->p_memsz;
	}
	if (lo >= hi) {
		show_error("no loadable segments");
		return 0;
	}

	// The image_size is the bytes the file provides (up to the end of the last filesz). The bss_size is the bytes
	// after that (memsz - filesz of segments whose file data ends before hi, plus trailing zero-only segments).
	// For simplicity, compute image_size as the highest (paddr + filesz) - lo, and bss_size as the rest.
	uint32_t file_hi = lo;
	for (int i = 0; i < ehdr->e_phnum; i++) {
		const Elf32_Phdr *phdr = (const Elf32_Phdr *)((const uint8_t *)elf_data + ehdr->e_phoff +
			i * sizeof(Elf32_Phdr));
		if (phdr->p_type != PT_LOAD || phdr->p_memsz == 0)
			continue;
		uint32_t seg_file_end = phdr->p_paddr + phdr->p_filesz;
		if (seg_file_end > file_hi)
			file_hi = seg_file_end;
	}

	uint32_t image_size = file_hi - lo;
	uint32_t bss_size = hi - file_hi;

	xsdk_log_write("tinyxell: ELF load range %08x..%08x (image %u, bss %u), entry %08x",
		(unsigned)lo, (unsigned)hi, (unsigned)image_size, (unsigned)bss_size, (unsigned)ehdr->e_entry);

	// The ELF's paddrs have the 0x80000000 mapping bit set for standard libxenon/xsdk titles; the physical extent is
	// the low 31 bits.
	uint32_t phys_hi = hi & 0x7FFFFFFFu;
	if (phys_hi > TINYXELL_PHYS_LIMIT) {
		show_error("ELF extends past the stage1 load address");
		return 0;
	}

	// Allocate physical memory for the image below TINYXELL_PHYS_LIMIT. Only the file-backed portion needs to be
	// allocated; stage1 will zero the bss in place after copying.
	uint32_t alloc_size = (image_size + 0xFFF) & ~0xFFFu; // page-align
	if (alloc_size < 0x10000)
		alloc_size = 0x10000; // MmAllocatePhysicalMemoryEx minimum
	uint8_t *image = MmAllocatePhysicalMemoryEx(0, alloc_size, PAGE_READWRITE, 0, TINYXELL_PHYS_LIMIT - 1, 0);
	if (!image) {
		show_error("could not allocate physical memory for the image");
		return 0;
	}
	memset(image, 0, alloc_size);

	uint32_t phys_base = MmGetPhysicalAddress(image);
	xsdk_log_write("tinyxell: allocated %u bytes at physical %08x (virtual %p)",
		(unsigned)alloc_size, (unsigned)phys_base, (void *)image);

	// Second pass: copy each segment's file data into the allocation. The allocation sits at physical phys_base, but
	// the ELF's segments address from lo; the offset into the allocation is (paddr - lo).
	for (int i = 0; i < ehdr->e_phnum; i++) {
		const Elf32_Phdr *phdr = (const Elf32_Phdr *)((const uint8_t *)elf_data + ehdr->e_phoff +
			i * sizeof(Elf32_Phdr));
		if (phdr->p_type != PT_LOAD || phdr->p_memsz == 0)
			continue;
		if (phdr->p_filesz == 0)
			continue;
		if (phdr->p_offset + phdr->p_filesz > elf_size) {
			show_error("segment data past EOF");
			MmFreePhysicalMemory(0, image);
			return 0;
		}
		uint32_t offset = phdr->p_paddr - lo;
		memcpy(image + offset, (const uint8_t *)elf_data + phdr->p_offset, phdr->p_filesz);
		xsdk_log_write("tinyxell:   segment %d: %08x +%08x (%08x file) -> offset %08x",
			i, (unsigned)phdr->p_paddr, (unsigned)phdr->p_memsz, (unsigned)phdr->p_filesz, (unsigned)offset);
	}

	*out_image = image;
	*out_image_size = image_size;
	*out_bss_size = bss_size;
	// The ELF's virtual addresses have 0x80000000 set (the 32-bit mapping); the physical address is the low 31 bits.
	*out_load_base = lo & 0x7FFFFFFFu;
	return ehdr->e_entry;
}

// ---------------------------------------------------------------------------
// Patch the handoff struct inside the stage1 blob and launch
// ---------------------------------------------------------------------------

static void launch(uint8_t *image, uint32_t image_size, uint32_t bss_size, uint32_t entry, uint32_t load)
{
	// Copy stage1 into a buffer we can patch (it's const in .rodata from stage1.h).
	uint8_t *blob = malloc(tinyxell_stage1_len);
	if (!blob) {
		show_error("could not allocate stage1 copy");
		return;
	}
	memcpy(blob, tinyxell_stage1, tinyxell_stage1_len);

	// Find the handoff struct by scanning for the magic. It's in .data, at a known offset from the stage1 build, but
	// scanning is safer across rebuilds.
	struct tinyxell_handoff *ho = NULL;
	for (uint32_t off = 0; off + sizeof(struct tinyxell_handoff) <= tinyxell_stage1_len; off += 4) {
		uint32_t *p = (uint32_t *)(blob + off);
		if (*p == TINYXELL_HANDOFF_MAGIC) {
			ho = (struct tinyxell_handoff *)p;
			break;
		}
	}
	if (!ho) {
		show_error("handoff magic not found in stage1 blob");
		free(blob);
		return;
	}

	uint32_t phys_source = MmGetPhysicalAddress(image);
	ho->source = phys_source;
	ho->size = image_size;
	ho->bss_size = bss_size;
	ho->load = load;
	ho->entry = entry;

	xsdk_log_write("tinyxell: handoff: source=%08x size=%08x bss=%08x load=%08x entry=%08x",
		(unsigned)ho->source, (unsigned)ho->size, (unsigned)ho->bss_size,
		(unsigned)ho->load, (unsigned)ho->entry);

	xsdk_log_write("tinyxell: launching stage1 (%u bytes) to %08x",
		(unsigned)tinyxell_stage1_len, (unsigned)(TINYXELL_STAGE1_ADDR & 0xFFFFFFFF));

	// This does not return on success.
	hv_execute(TINYXELL_STAGE1_ADDR, blob, tinyxell_stage1_len);

	show_error("hv_execute returned (the hypervisor call failed)");
	free(blob);
}

// ---------------------------------------------------------------------------
// Entry
// ---------------------------------------------------------------------------

int main(void)
{
	xsdk_log_write("tinyxell launcher");

	// Step 1: ensure we have a hypervisor backdoor.
	if (!hv_syscall_zero_backdoor_installed()) {
		xsdk_log_write("tinyxell: no syscall 0 backdoor, installing HV expansion");
		uint64_t ret = hv_install_expansion_backdoor();
		if (ret != 0) {
			char msg[128];
			(void)snprintf(msg, sizeof msg,
				"No HV backdoor available (expansion install returned 0x%llx)",
				(unsigned long long)ret);
			show_error(msg);
			return 1;
		}
		xsdk_log_write("tinyxell: HV expansion installed");
	} else {
		xsdk_log_write("tinyxell: syscall 0 backdoor present");
	}

	// Step 2: load the homebrew ELF.
	uint32_t elf_size = 0;
	void *elf_data = try_load_elf_file(&elf_size);
	if (!elf_data) {
		show_error("No homebrew ELF found beside the .xex");
		return 1;
	}
	xsdk_log_write("tinyxell: loaded ELF (%u bytes)", (unsigned)elf_size);

	// Step 3: parse and flatten the ELF into physical memory.
	uint8_t *image = NULL;
	uint32_t image_size = 0;
	uint32_t bss_size = 0;
	uint32_t load_base = 0;
	uint32_t entry = flatten_elf(elf_data, elf_size, &image, &image_size, &bss_size, &load_base);
	free(elf_data);
	if (entry == 0 && image == NULL)
		return 1;

	// The ELF's entry point is a virtual address with the 0x80000000 mapping bit; the physical entry is the low 31.
	uint32_t phys_entry = entry & 0x7FFFFFFFu;

	xsdk_log_write("tinyxell: phys_entry=%08x load_base=%08x", (unsigned)phys_entry, (unsigned)load_base);

	// Step 4: launch.
	launch(image, image_size, bss_size, phys_entry, load_base);

	// If we get here, something failed.
	MmFreePhysicalMemory(0, image);
	return 1;
}
